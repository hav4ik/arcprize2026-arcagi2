"""Review files for Manh: our built notebook vs his, cell by cell, plus our pinned solver / harness vs the ones in his
cell 0b. Usage: python3 review_vs_manh.py OURS.ipynb HIS.ipynb OUTDIR (writes cells_vs_manh.md, solver_vs_manh.diff,
harness_vs_manh.diff). Reads both notebooks as data; the pinned bundles are base64 tar.gz blobs, extracted file by file."""
import base64, difflib, hashlib, io, json, re, subprocess, sys, tarfile, tempfile
from pathlib import Path


def cells(p):
    return ["".join(c["source"]) for c in json.load(open(p))["cells"]]


def squash(t):
    out = []
    for l in t.splitlines():
        if len(l) > 400:
            m = re.match(r'(\s*\w+\s*=\s*r?")', l)
            out.append((m.group(1) if m else "") + f"<{len(l)} chars, sha256 {hashlib.sha256(l.encode()).hexdigest()[:12]}>")
        else:
            out.append(l)
    return out


def bundle(cs, dest):
    c = next(x for x in cs if x.startswith("# Cell 0b"))
    for b in re.findall(r'\w+\s*=\s*"([A-Za-z0-9+/=]{1000,})"', c):
        with tarfile.open(fileobj=io.BytesIO(base64.b64decode(b)), mode="r:*") as tf:
            for m in tf.getmembers():
                if m.isfile() and not m.name.startswith("/") and ".." not in m.name.split("/"):
                    p = dest / m.name
                    p.parent.mkdir(parents=True, exist_ok=True)
                    p.write_bytes(tf.extractfile(m).read())


def main(ours_p, his_p, out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    ours, his = cells(ours_p), cells(his_p)
    j, rows, diff = 0, [], []
    for i, c in enumerate(ours):
        head = c.splitlines()[0][:90] if c else ""
        if j < len(his) and c == his[j]:
            rows.append((i, "his, unchanged", head))
            j += 1
        elif j < len(his) and c.splitlines()[:1] and his[j].splitlines()[:1] and \
                c.splitlines()[0][:14] == his[j].splitlines()[0][:14] or (i == 1 and j == 1):
            d = list(difflib.unified_diff(squash(his[j]), squash(c), f"his cell {j}", f"ours cell {i}", lineterm="", n=2))
            n = sum(1 for l in d if l[:1] in "+-" and l[:3] not in ("+++", "---"))
            rows.append((i, f"OURS, changed vs his cell {j} ({n} lines)", head))
            diff += [f"### cell {i} (changed vs his cell {j}): {head}", "```diff"] + d + ["```", ""]
            j += 1
        else:
            rows.append((i, "OURS, inserted", head))
            diff += [f"### cell {i} (inserted): {head}", "```diff"] + ["+" + l for l in squash(c)] + ["```", ""]
    assert j == len(his), f"his cells not all accounted for: {j} of {len(his)}"
    sha = hashlib.sha256(open(ours_p, "rb").read()).hexdigest()[:12]
    with open(out / "cells_vs_manh.md", "w") as f:
        f.write(f"# Our notebook (sha256 {sha}) vs Manh's, cell by cell (generated by review_vs_manh.py)\n\n"
                "Long base64 lines are shown as <N chars, sha256>.\n\n| ours | status | first line |\n|---|---|---|\n")
        for i, s, h in rows:
            f.write(f"| {i} | {s} | `{h.replace('|', '/')}` |\n")
        f.write("\n" + "\n".join(diff) + "\n")
    with tempfile.TemporaryDirectory() as t:
        t = Path(t)
        bundle(his, t / "his")
        bundle(ours, t / "ours")
        for name, rel in (("solver", "solver_dsv41.py"), ("harness", "repo/evals/run_deepseek_tools.py")):
            r = subprocess.run(["diff", "-u", "--label", f"his {rel}", "--label", f"ours {rel}", t / "his" / rel,
                                t / "ours" / rel], capture_output=True, text=True)
            (out / f"{name}_vs_manh.diff").write_text(r.stdout)
        same = [str(p.relative_to(t / "ours")) for p in sorted((t / "ours").rglob("*")) if p.is_file()
                and (t / "his" / p.relative_to(t / "ours")).exists()
                and p.read_bytes() == (t / "his" / p.relative_to(t / "ours")).read_bytes()]
    for i, s, h in rows:
        print(f"{i:2d} {s:42s} {h[:60]}")
    print("pinned files identical to his:", same)


if __name__ == "__main__":
    main(*sys.argv[1:4])
