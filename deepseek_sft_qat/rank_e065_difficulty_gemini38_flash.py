def build_difficulty_prompt(rec: dict[str, Any], compact: bool = False) -> str:
    """Formats a compact prompt summarizing the task and DeepSeek's rollout output."""
    tid = rec.get("task_id", "")
    src = rec.get("source", "")
    n_train = rec.get("n_train_pairs", 0)
    n_test = rec.get("n_test_pairs", 1)
    train_shapes = rec.get("train_shapes", [])
    test_shapes = rec.get("test_shapes", [])

    test_passing = bool(rec.get("test_passing"))
    train_pass = bool(rec.get("train_pass"))
    train_frac = float(rec.get("train_frac") or 0.0)
    txt_pass = bool(rec.get("text_twin_test_passing"))
    failure_cat = rec.get("failure_category", "")
    turns = int(rec.get("turns") or 0)
    tool_calls = int(rec.get("tool_calls") or 0)
    comp_tokens = int(rec.get("completion_tokens") or 0)
    reas_tokens = int(rec.get("reasoning_tokens") or 0)
    py_errs = int(rec.get("py_error_turns") or 0)
    stop_reason = rec.get("stop_reason", "")

    pair_summaries = []
    for pc in rec.get("pair_checks", []):
        ds = pc.get("diff_summary") or {}
        pair_summaries.append(
            {
                "pair": pc.get("pair", 0),
                "exact_gt_match": pc.get("exact_gt_match"),
                "status": ds.get("status"),
                "gt_shape": ds.get("gt_shape"),
                "pred_shape": ds.get("pred_shape"),
                "cell_accuracy": ds.get("cell_accuracy"),
                "mismatched_cells": ds.get("mismatched_cells"),
            }
        )

    r1_lim = 350 if compact else 900
    r2_lim = 450 if compact else 1200
    c_lim = 550 if compact else 1600
    t_lim = 250 if compact else 600
    first_reas = (rec.get("first_reasoning_excerpt") or "")[:r1_lim]
    last_reas = (rec.get("last_reasoning_excerpt") or "")[:r2_lim]
    code_str = (rec.get("last_submit_code") or rec.get("last_python_code") or "")[:c_lim]
    tool_out = (rec.get("last_tool_output") or "")[:t_lim]

    return (
        f"Task ID: {tid} (source={src}, n_train_pairs={n_train}, n_test_pairs={n_test})\n"
        f"Train shapes: {json.dumps(train_shapes)} | Test shapes: {json.dumps(test_shapes)}\n"
        f"Telemetry: image_test_passing={test_passing}, train_pass={train_pass} (train_frac={train_frac:.3f}), "
        f"text_twin_test_passing={txt_pass}, category={failure_cat} (stop={stop_reason}), "
        f"turns={turns}, tool_calls={tool_calls}, completion_tokens={comp_tokens}, "
        f"reasoning_tokens={reas_tokens}, py_error_turns={py_errs}\n"
        f"Test pair check: {json.dumps(pair_summaries)}\n"
        f"Initial Reasoning: {first_reas}\n"
        f"Final Reasoning: {last_reas}\n"
        f"Submitted Code:\n{code_str}\n"
        f"Last Sandbox Output: {tool_out}\n"
    )


def build_batch_difficulty_prompt(recs: list[dict[str, Any]]) -> str:
    """Formats a batch of rollout records for a single Gemini Flash 3.8 JSON call."""
    parts = [
        f"Evaluate the following {len(recs)} ARC-AGI-2 / NVARC tasks and return the JSON object {{\"ratings\": [...]}} with one entry per task_id:\n"
    ]
    for idx, r in enumerate(recs, start=1):
        parts.append(f"--- ITEM {idx} OF {len(recs)} (task_id={r.get('task_id')}) ---\n" + build_difficulty_prompt(r, compact=True))
    return "\n".join(parts)


def _normalize_parsed_rating(parsed: dict[str, Any], model_version: str = "gemini-3.8-flash") -> dict[str, Any]:
    score = float(parsed.get("difficulty_score", 5.0))
    score = max(1.0, min(10.0, score))
    steps = int(parsed.get("rule_complexity_steps", 3) or 3)
    steps = max(1, min(10, steps))
    tier = str(parsed.get("difficulty_tier", "Tier2_Hard"))
    if tier not in (
        "Tier1_Extreme",
        "Tier2_Hard",
        "Tier3_Medium",
        "Tier4_Easy",
    ):
        if score >= 8.0:
            tier = "Tier1_Extreme"
        elif score >= 6.0:
            tier = "Tier2_Hard"
        elif score >= 3.5:
            tier = "Tier3_Medium"
        else:
            tier = "Tier4_Easy"
    risk = str(parsed.get("overfit_or_edge_case_risk", "medium")).lower()
    if risk not in ("high", "medium", "low"):
        risk = "medium"
    return {
        "gemini_ok": True,
        "model_version": model_version,
        "difficulty_score": round(score, 2),
        "difficulty_tier": tier,
        "transformation_category": str(parsed.get("transformation_category", "unknown"))[:80],
        "rule_complexity_steps": steps,
        "overfit_or_edge_case_risk": risk,
        "reasoning_bottleneck": str(parsed.get("reasoning_bottleneck", ""))[:500],
    }


def _extract_json_dict(raw_text: str) -> dict[str, Any] | None:
    text = raw_text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*", "", text)
        text = re.sub(r"\s*```$", "", text)
    start = text.find("{")
    end = text.rfind("}")
    if start == -1 or end == -1 or end <= start:
        return None
    snippet = text[start : end + 1]
    try:
        obj = json.loads(snippet)
        return obj if isinstance(obj, dict) else None
    except Exception:  # pylint: disable=broad-exception-caught
        return None


def call_gemini_flash38(
    prompt: str,
    generate_cli_binary: str = "/google/bin/releases/gemini-agents-generate/generate",
    model_name: str = "models/gemini-3.8-flash",
    timeout_s: float = 45.0,
    max_retries: int = 4,
) -> dict[str, Any]:
    """Calls Gemini Flash 3.8 via `/google/bin/releases/gemini-agents-generate/generate -prod -json`."""
    payload = {
        "model": model_name,
        "system_instruction": {"parts": [{"text": DIFFICULTY_SYSTEM_PROMPT}]},
        "contents": [
            {
                "role": "user",
                "parts": [{"text": prompt}],
            }
        ],
        "generation_config": {
            "temperature": 0.1,
            "max_output_tokens": 1024,
        },
    }
    input_bytes = json.dumps(payload).encode("utf-8")

    last_err = ""
    for attempt in range(max_retries):
        try:
            proc = subprocess.run(
                [generate_cli_binary, "-prod", "-json"],
                input=input_bytes,
                capture_output=True,
                timeout=timeout_s,
                check=False,
            )
            if proc.returncode == 0 and proc.stdout:
                resp = json.loads(proc.stdout.decode("utf-8", errors="replace"))
                cands = resp.get("candidates") or []
                if cands:
                    parts = (cands[0].get("content") or {}).get("parts") or []
                    text_parts = [
                        str(p.get("text", ""))
                        for p in parts
                        if isinstance(p, dict) and not p.get("thought", False) and p.get("text")
                    ]
                    if not text_parts:
                        text_parts = [
                            str(p.get("text", ""))
                            for p in parts
                            if isinstance(p, dict) and p.get("text")
                        ]
                    joined = "\n".join(text_parts)
                    parsed = _extract_json_dict(joined)
                    if parsed is not None and "difficulty_score" in parsed:
                        return _normalize_parsed_rating(
                            parsed, model_version=resp.get("model_version", "gemini-3.8-flash")
                        )
                    last_err = f"unparseable_json: {joined[:200]}"
                else:
                    last_err = "empty_candidates"
            else:
                last_err = (
                    proc.stderr.decode("utf-8", errors="replace")[:240]
                    if proc.stderr
                    else f"rc={proc.returncode}"
                )
        except Exception as e:  # pylint: disable=broad-exception-caught
            last_err = str(e)[:240]
        time.sleep(1.2 * (2 ** attempt))

    return _heuristic_difficulty_fallback(last_err)


def call_gemini_flash38_batch(
    recs: list[dict[str, Any]],
    generate_cli_binary: str = "/google/bin/releases/gemini-agents-generate/generate",
    model_name: str = "models/gemini-3.8-flash",
    timeout_s: float = 90.0,
    max_retries: int = 5,
) -> dict[str, dict[str, Any]]:
    """Evaluates a batch of rollout records in a single Gemini Flash 3.8 call."""
    if not recs:
        return {}
    if len(recs) == 1:
        r0 = recs[0]
        return {str(r0["task_id"]): call_gemini_flash38(build_difficulty_prompt(r0), generate_cli_binary, model_name)}

    prompt = build_batch_difficulty_prompt(recs)
    payload = {
        "model": model_name,
        "system_instruction": {"parts": [{"text": BATCH_DIFFICULTY_SYSTEM_PROMPT}]},
        "contents": [{"role": "user", "parts": [{"text": prompt}]}],
        "generation_config": {
            "temperature": 0.1,
            "max_output_tokens": 8192,
        },
    }
    input_bytes = json.dumps(payload).encode("utf-8")

    last_err = ""
    for attempt in range(max_retries):
        try:
            proc = subprocess.run(
                [generate_cli_binary, "-prod", "-json"],
                input=input_bytes,
                capture_output=True,
                timeout=timeout_s,
                check=False,
            )
            if proc.returncode == 0 and proc.stdout:
                resp = json.loads(proc.stdout.decode("utf-8", errors="replace"))
                model_ver = resp.get("model_version", "gemini-3.8-flash")
                cands = resp.get("candidates") or []
                if cands:
                    parts = (cands[0].get("content") or {}).get("parts") or []
                    text_parts = [
                        str(p.get("text", ""))
                        for p in parts
                        if isinstance(p, dict) and not p.get("thought", False) and p.get("text")
                    ]
                    if not text_parts:
                        text_parts = [
                            str(p.get("text", ""))
                            for p in parts
                            if isinstance(p, dict) and p.get("text")
                        ]
                    joined = "\n".join(text_parts)
                    parsed = _extract_json_dict(joined)
                    ratings_list = None
                    if isinstance(parsed, dict) and isinstance(parsed.get("ratings"), list):
                        ratings_list = parsed["ratings"]
                    if ratings_list:
                        by_tid: dict[str, dict[str, Any]] = {}
                        for idx, item in enumerate(ratings_list):
                            if not isinstance(item, dict) or "difficulty_score" not in item:
                                continue
                            tid = str(item.get("task_id") or "")
                            if not tid and idx < len(recs):
                                tid = str(recs[idx]["task_id"])
                            if tid:
                                by_tid[tid] = _normalize_parsed_rating(item, model_version=model_ver)
                        if len(by_tid) == len(recs):
                            return by_tid
                        # Fill any missing items individually
                        for r in recs:
                            rtid = str(r["task_id"])
                            if rtid not in by_tid:
                                by_tid[rtid] = call_gemini_flash38(
                                    build_difficulty_prompt(r),
                                    generate_cli_binary=generate_cli_binary,
                                    model_name=model_name,
                                )
                        return by_tid
                    last_err = f"unparseable_batch_json: {joined[:200]}"
                else:
                    last_err = "empty_candidates"
            else:
                last_err = (
                    proc.stderr.decode("utf-8", errors="replace")[:240]
                    if proc.stderr
                    else f"rc={proc.returncode}"
                )
        except Exception as e:  # pylint: disable=broad-exception-caught
            last_err = str(e)[:240]
        time.sleep(1.5 * (2 ** attempt))

    return {str(r["task_id"]): _heuristic_difficulty_fallback(last_err) for r in recs}


def _heuristic_difficulty_fallback(err_msg: str) -> dict[str, Any]:
    return {
        "gemini_ok": False,
        "model_version": "heuristic_fallback",
        "difficulty_score": 7.0,
        "difficulty_tier": "Tier2_Hard",
        "transformation_category": "multi_step_compositional",
        "rule_complexity_steps": 4,
        "overfit_or_edge_case_risk": "high",
        "reasoning_bottleneck": f"Fallback rating (CLI error: {err_msg})",
    }


def compute_composite_hardness_score(
    rec: dict[str, Any],
    gemini_rating: dict[str, Any],
) -> float:
    """Computes a 0..100 composite hardness score combining Gemini 3.8 Flash rating + DeepSeek empirical outcome."""
    # 1. Gemini Flash 3.8 difficulty_score (1..10) -> 0..55 points
    g_score = float(gemini_rating.get("difficulty_score", 5.0))
    pts = (g_score / 10.0) * 55.0

    # 2. Empirical outcome penalty (0..25 points)
    img_pass = bool(rec.get("test_passing"))
    train_pass = bool(rec.get("train_pass"))
    txt_pass = bool(rec.get("text_twin_test_passing"))
    if not img_pass and not txt_pass:
        pts += 22.0 if not train_pass else 19.0
    elif not img_pass and txt_pass:
        pts += 14.0
    elif img_pass and not txt_pass:
        pts += 8.0
    elif img_pass and not train_pass:
        pts += 6.0

    # 3. Token & turn effort (0..20 points)
    comp_tokens = min(64000, max(0, int(rec.get("completion_tokens") or 0)))
    turns = min(25, max(0, int(rec.get("turns") or 0)))
    py_errs = min(10, max(0, int(rec.get("py_error_turns") or 0)))
    pts += (comp_tokens / 64000.0) * 12.0
    pts += (turns / 25.0) * 5.0
    pts += (py_errs / 10.0) * 3.0

    return round(min(100.0, max(0.0, pts)), 2)


def run_difficulty_ranking(
    telemetry_jsonl_path: str,
    output_dir: str,
    generate_cli_binary: str = "/google/bin/releases/gemini-agents-generate/generate",
    gemini_model: str = "models/gemini-3.8-flash",
    scope: str = "all",
    max_workers: int = 6,
    tasks_per_call: int = 10,
    limit: int = 0,
    cns_quota_group: str = "deepmind-resources-colossus",
) -> dict[str, Any]:
    """Runs Gemini Flash 3.8 difficulty ranking with incremental CNS checkpointing."""
    t0 = time.time()
    export_and_quantize.ensure_cns_quota_dir(output_dir, group=cns_quota_group)

    records: list[dict[str, Any]] = []
    with gfile.GFile(telemetry_jsonl_path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            records.append(json.loads(line))

    if scope == "non_test_passing":
        records = [r for r in records if not r.get("test_passing")]

    # Prioritize non-test-passing rollouts first (ordered by completion_tokens desc), then test-passing
    records.sort(
        key=lambda r: (
            0 if not r.get("test_passing") else 1,
            -int(r.get("completion_tokens") or 0),
            str(r.get("task_id", "")),
        )
    )
    if limit > 0:
        records = records[:limit]

    checkpoint_path = os.path.join(output_dir, "gemini38_flash_checkpoint.jsonl")
    completed_by_task: dict[str, dict[str, Any]] = {}
    if gfile.Exists(checkpoint_path):
        with gfile.GFile(checkpoint_path, "r") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    obj = json.loads(line)
                    tid = str(obj.get("task_id", ""))
                    if tid and obj.get("gemini_ok", False):
                        completed_by_task[tid] = obj
                except Exception:  # pylint: disable=broad-exception-caught
                    continue
        # Rewrite checkpoint keeping only gemini_ok=True rows
        with gfile.GFile(checkpoint_path, "w") as f:
            for obj in completed_by_task.values():
                f.write(json.dumps(obj) + "\n")

    pending = [r for r in records if str(r["task_id"]) not in completed_by_task]
    print(
        f"[gemini-3.8-flash] total_in_scope={len(records)}, "
        f"already_checkpointed_ok={len(completed_by_task)}, pending={len(pending)} "
        f"(tasks_per_call={tasks_per_call}, max_workers={max_workers})",
        flush=True,
    )

    write_lock = threading.Lock()
    done_count = 0

    def _eval_batch(batch_recs: list[dict[str, Any]]) -> list[dict[str, Any]]:
        ratings_by_tid = call_gemini_flash38_batch(
            recs=batch_recs,
            generate_cli_binary=generate_cli_binary,
            model_name=gemini_model,
        )
        out_rows: list[dict[str, Any]] = []
        for rec in batch_recs:
            tid = str(rec["task_id"])
            rating = ratings_by_tid.get(tid) or _heuristic_difficulty_fallback("missing_from_batch")
            comp_score = compute_composite_hardness_score(rec, rating)
            out_rows.append(
                {
                    "task_id": tid,
                    "parent": rec.get("parent", ""),
                    "source": rec.get("source", ""),
                    "source_file": rec.get("source_file", ""),
                    "test_passing": bool(rec.get("test_passing")),
                    "train_pass": bool(rec.get("train_pass")),
                    "train_frac": float(rec.get("train_frac") or 0.0),
                    "text_twin_test_passing": bool(rec.get("text_twin_test_passing")),
                    "text_twin_train_pass": bool(rec.get("text_twin_train_pass")),
                    "is_contaminated": bool(rec.get("is_contaminated")),
                    "failure_category": rec.get("failure_category", ""),
                    "turns": int(rec.get("turns") or 0),
                    "tool_calls": int(rec.get("tool_calls") or 0),
                    "completion_tokens": int(rec.get("completion_tokens") or 0),
                    "reasoning_tokens": int(rec.get("reasoning_tokens") or 0),
                    "py_error_turns": int(rec.get("py_error_turns") or 0),
                    "stop_reason": str(rec.get("stop_reason") or ""),
                    "answer_source": str(rec.get("answer_source") or ""),
                    **rating,
                    "composite_hardness_score": comp_score,
                }
            )
        return out_rows

    if pending:
        bsize = max(1, int(tasks_per_call))
        batches = [pending[i : i + bsize] for i in range(0, len(pending), bsize)]
        with gfile.GFile(checkpoint_path, "a") as ckpt_f:
            with ThreadPoolExecutor(max_workers=max_workers) as pool:
                fut_map = {pool.submit(_eval_batch, b): idx for idx, b in enumerate(batches)}
                for fut in as_completed(fut_map):
                    batch_rows = fut.result()
                    with write_lock:
                        ok_in_batch = 0
                        for res in batch_rows:
                            completed_by_task[res["task_id"]] = res
                            if res.get("gemini_ok"):
                                ckpt_f.write(json.dumps(res) + "\n")
                                ok_in_batch += 1
                        done_count += len(batch_rows)
                        ckpt_f.flush()
                        if done_count % 100 < bsize or done_count == len(pending):
                            elapsed = time.time() - t0
                            rate = done_count / max(elapsed, 1e-3)
                            ok_tot = sum(1 for v in completed_by_task.values() if v.get("gemini_ok"))
                            print(
                                f"[gemini-3.8-flash] {done_count}/{len(pending)} "
                                f"(gemini_ok_total={ok_tot}, {rate:.1f} tasks/s, elapsed={elapsed:.1f}s)",
                                flush=True,
                            )

    # Combine all evaluated records in scope and assign global rank (1 = hardest)
    all_ranked = [
        completed_by_task[str(r["task_id"])]
        for r in records
        if str(r["task_id"]) in completed_by_task
    ]
    all_ranked.sort(
        key=lambda x: (
            -float(x["composite_hardness_score"]),
            -float(x["difficulty_score"]),
            -int(x["completion_tokens"]),
            str(x["task_id"]),
        )
    )
    for idx, item in enumerate(all_ranked, start=1):
        item["hardness_rank"] = idx

    # Write final sorted JSONL, non-test-passing ranked JSONL, and Parquet to CNS
    ranked_jsonl_path = os.path.join(output_dir, "gemini38_flash_difficulty_rankings.jsonl")
    with gfile.GFile(ranked_jsonl_path, "w") as f:
        for item in all_ranked:
            f.write(json.dumps(item) + "\n")

    non_pass_ranked = [x for x in all_ranked if not x["test_passing"]]
    for idx, item in enumerate(non_pass_ranked, start=1):
        item["non_test_passing_hardness_rank"] = idx

    non_pass_ranked_path = os.path.join(
        output_dir, "gemini38_flash_non_test_passing_ranked.jsonl"
    )
    with gfile.GFile(non_pass_ranked_path, "w") as f:
        for item in non_pass_ranked:
            f.write(json.dumps(item) + "\n")

    ranked_parquet_path = os.path.join(output_dir, "gemini38_flash_difficulty_rankings.parquet")
    if all_ranked:
        tbl = pa.Table.from_pylist(all_ranked)
        buf = io.BytesIO()
        pq.write_table(tbl, buf, compression="zstd")
        with gfile.GFile(ranked_parquet_path, "wb") as f:
            f.write(buf.getvalue())

    tier_counts_all = Counter(x["difficulty_tier"] for x in all_ranked)
    tier_counts_fail = Counter(x["difficulty_tier"] for x in non_pass_ranked)
    cat_counts_fail = Counter(x["transformation_category"] for x in non_pass_ranked)

    pass_scores = [x["difficulty_score"] for x in all_ranked if x["test_passing"]]
    fail_scores = [x["difficulty_score"] for x in non_pass_ranked]

    summary = {
        "created_at_unix": time.time(),
        "elapsed_s": round(time.time() - t0, 2),
        "model": gemini_model,
        "scope": scope,
        "total_ranked": len(all_ranked),
        "gemini_ok_count": sum(1 for x in all_ranked if x.get("gemini_ok")),
        "non_test_passing_ranked_count": len(non_pass_ranked),
        "mean_difficulty_score_all": (
            round(sum(x["difficulty_score"] for x in all_ranked) / len(all_ranked), 3)
            if all_ranked
            else 0.0
        ),
        "mean_difficulty_score_test_passing": (
            round(sum(pass_scores) / len(pass_scores), 3) if pass_scores else 0.0
        ),
        "mean_difficulty_score_non_test_passing": (
            round(sum(fail_scores) / len(fail_scores), 3) if fail_scores else 0.0
        ),
        "tier_distribution_all": dict(tier_counts_all),
        "tier_distribution_non_test_passing": dict(tier_counts_fail),
        "top_15_transformation_categories_non_test_passing": dict(
            cat_counts_fail.most_common(15)
        ),
        "top_10_hardest_questions": all_ranked[:10],
        "saved_cns_files": {
            "ranked_jsonl": ranked_jsonl_path,
            "non_test_passing_ranked_jsonl": non_pass_ranked_path,
            "ranked_parquet": ranked_parquet_path,
        },
    }
    summary_path = os.path.join(output_dir, "gemini38_flash_difficulty_summary.json")
    with gfile.GFile(summary_path, "w") as f:
        json.dump(summary, f, indent=2)

    return summary


