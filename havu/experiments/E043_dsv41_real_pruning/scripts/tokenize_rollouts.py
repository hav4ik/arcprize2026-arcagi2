#!/usr/bin/env python3
"""E043: rebuild exact DeepSeek-V4.1 token sequences for the E031/E036/E038 tool-use rollouts.

Each rollout (OpenAI chat messages with reasoning_content + tool_calls) is rendered with the model's own
encoding/encoding.py (thinking mode, tools on the system message, so earlier reasoning is kept), cut after
the last assistant message (later tool results were never consumed), and tokenized with tokenizer.json.

Output (one directory per split):
  tokens.u32   all sequences concatenated (uint32)
  roles.u8     1 = token generated by the model (an assistant span: reasoning, </think>, content, DSML calls,
               EOS); 0 = prompt/template/tool output (including the '<｜Assistant｜><think>' header)
  index.jsonl  one record per rollout: offset, length, n_gen, task/pair/batch/correct/train_pass and the
               API's per-turn prompt/completion token counts for a parity check

Usage: tokenize_rollouts.py --model-dir DIR --parquet a.parquet [b.parquet ...] --out OUTDIR
       [--effort 50] [--no-effort]
"""
import argparse
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np
import pyarrow.parquet as pq
from tokenizers import Tokenizer

# run_deepseek_tools.tools_for(mode=grid, answer_tool=True, helpers=False, tool_timeout=30), copied verbatim
RUN_PYTHON = ("Execute a Python cell in your persistent IPython session. Variables/functions persist. "
              "Preloaded: train (list of {'input': grid, 'output': grid}), test_input (grid), numpy as np. "
              "scipy is available. No internet or host files. Timeout 30s. "
              "Use print() to inspect results. Check transformations on all training pairs.")
SUBMIT_ANSWER = ("End this attempt with your test output. `code` is a Python expression evaluated in your session, "
                 "e.g. solve(test_input) or answer, giving a rectangular grid of ints 0-9 (list or numpy array); "
                 "statements that set a variable `answer` also work. The harness reads the grid directly: do not "
                 "retype it. Invalid grids return an error and the attempt continues.")


def harness_tools():
    return [{"type": "function", "function": {
        "name": name, "description": description,
        "parameters": {"type": "object", "properties": {"code": {"type": "string"}},
                       "required": ["code"], "additionalProperties": False},
    }} for name, description in (("run_python", RUN_PYTHON), ("submit_answer", SUBMIT_ANSWER))]


def load_encoding(model_dir):
    spec = importlib.util.spec_from_file_location("dsv41_encoding", Path(model_dir) / "encoding/encoding.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render_with_roles(enc, messages, effort, tools=True):
    """Return (text, spans) with spans = [(start, end)] char ranges of assistant (generated) renderings."""
    messages = [dict(m) for m in messages]
    last_asst = max(i for i, m in enumerate(messages) if m["role"] == "assistant")
    messages = messages[: last_asst + 1]
    if tools:
        if messages[0]["role"] != "system":  # runs without the effort header: tools go on an empty system message
            messages.insert(0, {"role": "system", "content": ""})
        messages[0]["tools"] = harness_tools()
    merged = enc.merge_tool_messages(messages)
    merged = enc.sort_tool_results_by_call_order(merged)
    merged, _ = enc.process_image_messages(merged)
    text, spans = enc.bos_token, []
    for idx, msg in enumerate(merged):
        piece = enc.render_message(idx, merged, thinking_mode="thinking", drop_thinking=False,
                                   reasoning_effort=effort)
        if msg["role"] == "assistant":
            spans.append((len(text), len(text) + len(piece)))
        text += piece
    ref = enc.encode_messages(messages, thinking_mode="thinking", reasoning_effort=effort)
    assert text == ref, "incremental render differs from encode_messages"
    return text, spans


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model-dir", required=True)
    ap.add_argument("--parquet", nargs="+", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--effort", type=int, default=50, help="numeric reasoning effort prefix (API 'low' = 50)")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--no-tools", action="store_true", help="single-turn no-tool rollouts (E044): no tool schemas")
    ap.add_argument("--shard", default="0/1", help="i/n: keep rows with global row index % n == i")
    args = ap.parse_args()

    enc = load_encoding(args.model_dir)
    tok = Tokenizer.from_file(str(Path(args.model_dir) / "tokenizer.json"))
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    ftok, frole = open(out / "tokens.u32", "wb"), open(out / "roles.u8", "wb")
    findex = open(out / "index.jsonl", "w")
    offset, n_rows, global_row = 0, 0, -1
    shard_i, shard_n = map(int, args.shard.split("/"))
    for path in args.parquet:
        table = pq.read_table(path)
        split = Path(path).stem
        for row in table.to_pylist():
            if args.limit and n_rows >= args.limit:
                break
            global_row += 1
            if global_row % shard_n != shard_i:
                continue
            messages = json.loads(row["messages"])
            if not any(m["role"] == "assistant" for m in messages):
                continue
            text, spans = render_with_roles(enc, messages, args.effort, tools=not args.no_tools)
            encoded = tok.encode(text, add_special_tokens=False)
            ids = np.asarray(encoded.ids, dtype=np.uint32)
            starts = np.asarray([s for s, _ in encoded.offsets], dtype=np.int64)
            roles = np.zeros(len(ids), dtype=np.uint8)
            for s, e in spans:
                roles[(starts >= s) & (starts < e)] = 1
            events = json.loads(row["events"]) if row.get("events") else []
            row = {**row, "train_pass": row.get("train_pass")}
            usage = [(e["usage"].get("prompt_tokens"), e["usage"].get("completion_tokens"))
                     for e in events if isinstance(e, dict) and e.get("usage")]
            if not usage and row.get("prompt_tokens") is not None:  # single-turn rows (E044 dataset)
                usage = [(int(row["prompt_tokens"]), int(row["completion_tokens"]))]
            elif not usage and row.get("usage"):  # single-turn eval rows (make_notool_eval_parquet.py)
                u = json.loads(row["usage"]) if isinstance(row["usage"], str) else row["usage"]
                usage = [(u.get("prompt_tokens"), u.get("completion_tokens"))]
            rec = {"split": split, "task_id": row["task_id"], "pair": row["pair"], "attempt": row["attempt"],
                   "batch": row.get("batch"), "parent": row.get("parent"), "correct": bool(row["correct"]),
                   "train_pass": row.get("train_pass"), "offset": offset, "length": int(len(ids)),
                   "n_gen": int(roles.sum()), "n_asst": len(spans), "api_usage": usage}
            ftok.write(ids.tobytes())
            frole.write(roles.tobytes())
            findex.write(json.dumps(rec) + "\n")
            offset += len(ids)
            n_rows += 1
            if n_rows % 500 == 0:
                print(f"{n_rows} rollouts, {offset / 1e6:.1f}M tokens", file=sys.stderr, flush=True)
    for f in (ftok, frole, findex):
        f.close()
    print(json.dumps({"rollouts": n_rows, "tokens": offset}))


if __name__ == "__main__":
    main()
